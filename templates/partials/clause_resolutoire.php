<?php /** @var int $num  numéro de l'article */
/*
 * Clause résolutoire — commune aux baux vide et meublé.
 * Réf. loi n° 89-462 du 6 juillet 1989, art. 24 (délais issus de la loi
 * n° 2023-668 du 27 juillet 2023) et art. 4 g) (troubles de voisinage).
 */ ?>
<h2>Article <?= (int) $num ?> — Clause résolutoire</h2>
<p class="article">Le présent bail sera résilié <strong>de plein droit</strong>, si bon semble au bailleur et sans qu'il
soit besoin de former une demande en justice autre que pour faire constater la résiliation :</p>
<ul class="article">
    <li>à défaut de paiement de tout ou partie du loyer ou des charges aux termes convenus, ou de versement du
        dépôt de garantie, <strong>six semaines</strong> après un commandement de payer demeuré infructueux ;</li>
    <li>à défaut de justification par le locataire d'une assurance contre les risques locatifs,
        <strong>un mois</strong> après un commandement demeuré infructueux ;</li>
    <li>en cas de non-respect par le locataire de son obligation d'user paisiblement des locaux loués, dès lors que
        ce manquement résulte de troubles de voisinage constatés par une décision de justice passée en force de
        chose jugée.</li>
</ul>
<p class="article">Le commandement de payer est délivré par commissaire de justice et reproduit les mentions prévues à
l'article 24 de la loi du 6 juillet 1989. Une fois la résiliation acquise, le locataire devra libérer les lieux ;
à défaut, son expulsion pourra être ordonnée par le juge des contentieux de la protection.</p>
