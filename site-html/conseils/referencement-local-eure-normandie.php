        <h2>1. La fiche Google Business Profile</h2>
        <p>C'est elle qui apparaît dans la carte. Elle est gratuite, et c'est souvent le levier le plus rapide pour une entreprise locale.</p>
        <ul>
          <li><strong>La bonne catégorie principale</strong> : « Plombier », « Fleuriste », « Société de sécurité »… C'est le critère le plus déterminant.</li>
          <li><strong>Votre zone d'intervention</strong> : les villes ou départements où vous travaillez, même si vous n'avez pas de local ouvert au public.</li>
          <li><strong>Horaires, services, photos</strong> : une fiche complète et vivante inspire confiance, à Google comme aux clients.</li>
          <li><strong>Des avis réguliers</strong>, et une réponse à chacun. Le nombre et la fraîcheur des avis pèsent dans le classement.</li>
          <li><strong>Un lien vers votre site</strong> : la fiche et le site se renforcent l'un l'autre.</li>
        </ul>

        <h2>2. Un site pensé pour vos recherches locales</h2>
        <p>Google classe des pages, pas des entreprises. Une page d'accueil qui parle de tout ne peut pas être la meilleure réponse à « électricien Louviers » <em>et</em> à « dépannage électrique Vernon ».</p>
        <ul>
          <li><strong>Une page par service</strong> : chaque prestation importante a sa page, avec un vrai texte qui explique ce que vous faites et pour qui.</li>
          <li><strong>Une page par ville ou secteur clé</strong>, avec un contenu propre à chaque ville. Des pages copiées-collées où seul le nom change sont repérées et ignorées par Google.</li>
          <li><strong>Des titres clairs</strong> : « Électricien à Vernon (27) | Nom de l'entreprise » plutôt que « Accueil ».</li>
          <li><strong>Un site rapide sur téléphone</strong> : la majorité des recherches locales se font sur mobile.</li>
        </ul>

        <h2>3. Les mêmes informations partout</h2>
        <p>Nom de l'entreprise, adresse et téléphone doivent être identiques sur votre site, votre fiche Google, les annuaires (Pages Jaunes, annuaires de la CCI ou de votre fédération), Facebook… Des versions différentes sèment le doute, pour Google comme pour vos clients. Profitez-en pour vérifier que vos anciennes adresses ou anciens numéros ne traînent plus nulle part.</p>

        <h2>Un exemple concret : ce site</h2>
        <p>Pertec.fr a été restructuré à l'automne 2026 sur ces principes : une page par ville de l'Eure et de Normandie, une page par secteur, des articles de conseils, une fiche Google reliée. Deux semaines plus tard, Search Console montrait déjà le site sur des recherches comme « création site internet vernon », « référencement web vernon » ou « devis site internet rouen ». La page de Vernon avait été affichée plus de 150 fois, encore en deuxième ou troisième page de résultats.</p>
        <p>C'est le fonctionnement normal : Google commence par tester un site sur des recherches proches, puis le fait progresser s'il répond bien. Le référencement se construit en semaines et en mois, pas en jours.</p>

        <h2>Ce qu'il ne faut pas faire</h2>
        <ul>
          <li><strong>Acheter de faux avis</strong> ou en écrire soi-même : c'est interdit, Google les supprime et peut sanctionner la fiche.</li>
          <li><strong>Créer de fausses adresses</strong> dans des villes où vous n'êtes pas installé pour apparaître sur la carte : les fiches sont suspendues.</li>
          <li><strong>Répéter le nom de la ville vingt fois</strong> dans une page : Google comprend très bien un texte naturel.</li>
          <li><strong>Croire aux promesses de « première place garantie »</strong> : personne ne contrôle le classement de Google.</li>
        </ul>

        <h2>Combien de temps et combien ça coûte ?</h2>
        <p>La fiche Google est gratuite et peut donner des résultats en quelques semaines si elle est bien remplie et reçoit des avis. Le référencement du site prend généralement quelques semaines à quelques mois, selon la concurrence dans votre métier et votre ville.</p>
